export const CUSTOM_MODELS_STORAGE_KEY = 'mh_custom_device_models_v1';

export function getCustomModels(): { brand: string; model: string }[] {
  if (typeof window === 'undefined') return [];
  try {
    const raw = localStorage.getItem(CUSTOM_MODELS_STORAGE_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw);
    if (Array.isArray(parsed)) return parsed;
  } catch (e) {
    console.error('Failed to load custom device models', e);
  }
  return [];
}

export function saveCustomModel(brand: string, model: string): boolean {
  if (!brand || !model || !brand.trim() || !model.trim()) return false;
  if (typeof window === 'undefined') return false;
  try {
    const cleanBrand = brand.trim();
    const cleanModel = model.trim();
    const current = getCustomModels();
    const exists = current.some(
      (item) =>
        item.brand.toLowerCase() === cleanBrand.toLowerCase() &&
        item.model.toLowerCase() === cleanModel.toLowerCase()
    );
    if (!exists) {
      current.unshift({ brand: cleanBrand, model: cleanModel });
      localStorage.setItem(CUSTOM_MODELS_STORAGE_KEY, JSON.stringify(current));
      invalidateModelCaches();
      window.dispatchEvent(new CustomEvent('custom-device-models-updated'));
      return true;
    }
  } catch (e) {
    console.error('Failed to save custom device model', e);
  }
  return false;
}

export function deleteCustomModel(brand: string, model: string): void {
  if (typeof window === 'undefined') return;
  try {
    const current = getCustomModels();
    const filtered = current.filter(
      (item) =>
        !(
          item.brand.toLowerCase() === brand.toLowerCase().trim() &&
          item.model.toLowerCase() === model.toLowerCase().trim()
        )
    );
    localStorage.setItem(CUSTOM_MODELS_STORAGE_KEY, JSON.stringify(filtered));
    invalidateModelCaches();
    window.dispatchEvent(new CustomEvent('custom-device-models-updated'));
  } catch (e) {
    console.error('Failed to delete custom model', e);
  }
}

// Memory caches for 60fps instant search without repeating JSON parses or heavy allocations
let cachedAllModels: { brand: string; model: string }[] | null = null;
let staticModelsCache: { brand: string; model: string }[] | null = null;
const brandModelsCache = new Map<string, string[]>();

function invalidateModelCaches() {
  cachedAllModels = null;
  brandModelsCache.clear();
}

function getStaticModels(): { brand: string; model: string }[] {
  if (staticModelsCache) return staticModelsCache;
  const list: { brand: string; model: string }[] = [];
  for (let i = 0; i < BRAND_MODELS_DATA.length; i++) {
    const b = BRAND_MODELS_DATA[i];
    for (let j = 0; j < b.models.length; j++) {
      list.push({ brand: b.brand, model: b.models[j] });
    }
  }
  staticModelsCache = list;
  return list;
}

export function getModelsForBrand(brandName: string): string[] {
  if (!brandName || brandName === 'All Brands') {
    return getAllModels().map((m) => m.model);
  }
  const normalizedKey = brandName.toLowerCase().trim();
  const cached = brandModelsCache.get(normalizedKey);
  if (cached) return cached;

  const custom = getCustomModels();
  const match = BRAND_MODELS_DATA.find(
    (b) => b.brand.toLowerCase() === normalizedKey
  );
  const baseModels = match ? match.models : [];
  const brandCustom = custom
    .filter((c) => c.brand.toLowerCase() === normalizedKey)
    .map((c) => c.model);

  const combined = Array.from(new Set([...brandCustom, ...baseModels]));
  brandModelsCache.set(normalizedKey, combined);
  return combined;
}

export function getAllModels(): { brand: string; model: string }[] {
  if (cachedAllModels) return cachedAllModels;
  const custom = getCustomModels();
  if (custom.length === 0) {
    cachedAllModels = getStaticModels();
    return cachedAllModels;
  }
  const set = new Set(custom.map((c) => `${c.brand.toLowerCase()}:::${c.model.toLowerCase()}`));
  const list: { brand: string; model: string }[] = [...custom];
  const staticList = getStaticModels();
  for (let i = 0; i < staticList.length; i++) {
    const item = staticList[i];
    const key = `${item.brand.toLowerCase()}:::${item.model.toLowerCase()}`;
    if (!set.has(key)) {
      list.push(item);
      set.add(key);
    }
  }
  cachedAllModels = list;
  return list;
}

export function searchAllModels(
  query: string,
  limit = 25
): { brand: string; model: string }[] {
  const all = getAllModels();
  if (!query || !query.trim()) return all.slice(0, limit);
  const q = query.toLowerCase().trim();
  const results: { brand: string; model: string }[] = [];
  for (const item of all) {
    if (item.model.toLowerCase().includes(q) || item.brand.toLowerCase().includes(q)) {
      results.push(item);
      if (results.length >= limit) return results;
    }
  }
  return results;
}

/**
 * Filter & sort models alphabetically A to Z, Z to A, or by letter.
 */
export function getModelsAtoZ(options?: {
  brand?: string;
  letter?: string;
  searchQuery?: string;
  sortOrder?: 'az' | 'za' | 'default';
  limit?: number;
}): { brand: string; model: string; fullDeviceName: string }[] {
  const {
    brand = 'All Brands',
    letter = 'ALL',
    searchQuery = '',
    sortOrder = 'az',
    limit = 500,
  } = options || {};

  let items = getAllModels();

  // Filter by Brand
  if (brand && brand !== 'All Brands') {
    items = items.filter(
      (item) => item.brand.toLowerCase() === brand.toLowerCase().trim()
    );
  }

  // Filter by search query
  if (searchQuery && searchQuery.trim()) {
    const q = searchQuery.toLowerCase().trim();
    items = items.filter(
      (item) =>
        item.model.toLowerCase().includes(q) ||
        item.brand.toLowerCase().includes(q)
    );
  }

  // Filter by Letter (A-Z or 0-9)
  if (letter && letter !== 'ALL') {
    if (letter === '0-9') {
      items = items.filter((item) => /^[0-9]/.test(item.model.trim()));
    } else {
      const targetChar = letter.toUpperCase();
      items = items.filter((item) =>
        item.model.trim().toUpperCase().startsWith(targetChar)
      );
    }
  }

  // Sort Order
  if (sortOrder === 'az') {
    items.sort((a, b) => a.model.localeCompare(b.model));
  } else if (sortOrder === 'za') {
    items.sort((a, b) => b.model.localeCompare(a.model));
  }

  return items.slice(0, limit).map((item) => ({
    ...item,
    fullDeviceName: formatDeviceBrandAndModel(item.brand, item.model),
  }));
}

/**
 * Formats a clean device name from brand and model, preventing duplicate brand names
 * (e.g. prevents "OnePlus OnePlus 12", "Apple Apple Watch Ultra", "boAt boAt Airdopes", etc.)
 */
export function formatDeviceBrandAndModel(brand?: string, model?: string): string {
  const cleanBrand = (brand || '').trim();
  const cleanModel = (model || '').trim();

  if (!cleanBrand || cleanBrand === 'Universal' || cleanBrand === 'All Brands') {
    return cleanModel;
  }
  if (!cleanModel) {
    return cleanBrand;
  }

  const lowerModel = cleanModel.toLowerCase();
  const lowerBrand = cleanBrand.toLowerCase();

  // If model already starts with the brand name (e.g. "OnePlus 12" under brand "OnePlus")
  if (lowerModel.startsWith(lowerBrand)) {
    return cleanModel;
  }

  // Handle composite slash brands like "Xiaomi / Redmi", "Nokia / HMD", "Nothing / CMF", "Honor / Huawei"
  if (cleanBrand.includes('/')) {
    const parts = cleanBrand.split('/').map((p) => p.trim());
    for (const part of parts) {
      if (part && lowerModel.startsWith(part.toLowerCase())) {
        return cleanModel;
      }
    }
  }

  // Handle "Google Pixel" where model starts with "Pixel" (e.g. "Pixel 9 Pro")
  if (lowerBrand === 'google pixel') {
    if (lowerModel.startsWith('pixel')) {
      return `Google ${cleanModel}`;
    }
    if (lowerModel.startsWith('google')) {
      return cleanModel;
    }
  }

  // If the first word of the brand and model match (e.g. "Apple" and "Apple Watch Ultra")
  const firstBrandWord = lowerBrand.split(/\s+/)[0];
  const firstModelWord = lowerModel.split(/\s+/)[0];
  if (firstBrandWord && firstBrandWord === firstModelWord) {
    return cleanModel;
  }

  return `${cleanBrand} ${cleanModel}`;
}
