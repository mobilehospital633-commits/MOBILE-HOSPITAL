export const ALL_BRANDS = BRAND_MODELS_DATA.map((b) => b.brand);

export function getModelsForBrand(brandName: string): string[] {
  const match = BRAND_MODELS_DATA.find(
    (b) => b.brand.toLowerCase() === brandName.toLowerCase()
  );
  return match ? match.models : [];
}

export function getAllModels(): { brand: string; model: string }[] {
  const list: { brand: string; model: string }[] = [];
  BRAND_MODELS_DATA.forEach((b) => {
    b.models.forEach((m) => {
      list.push({ brand: b.brand, model: m });
    });
  });
  return list;
}
